use std::path::PathBuf;

fn temp(name: &str) -> PathBuf {
    let dir =
        std::env::temp_dir().join(format!("keel_migrate_gate_{}_{}", std::process::id(), name));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn migrate_dry_run_and_keep_legacy_and_clean_upgrade() {
    let dir = temp("single");
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("lpp.toml"),
        r#"[package]
name = "legacy-app"
version = "0.1.0"
author = "Samar"
entry = "src/main.lpp"
description = "Legacy project"
license = "MIT"
"#,
    )
    .unwrap();
    std::fs::write(
        dir.join("lpp.lock"),
        "# L++ lockfile v2 — generated by lpp. Do not edit.\nlock_version = 2\n",
    )
    .unwrap();
    std::fs::write(dir.join("src/main.lpp"), "def main():\n    print(1)\n").unwrap();

    // 1. Dry-run leaves disk untouched.
    keel::commands::migrate::migrate(&dir, true, false).unwrap();
    assert!(dir.join("lpp.toml").is_file());
    assert!(dir.join("lpp.lock").is_file());
    assert!(!dir.join("Keel.toml").exists());
    assert!(!dir.join("Keel.lock").exists());

    // 2. Keep-legacy writes Keel.toml + Keel.lock and retains legacy files.
    keel::commands::migrate::migrate(&dir, false, true).unwrap();
    assert!(dir.join("Keel.toml").is_file());
    assert!(dir.join("Keel.lock").is_file());
    assert!(dir.join("lpp.toml").is_file());
    assert!(dir.join("lpp.lock").is_file());

    let parsed =
        lpp_pm::manifest::Manifest::parse(&std::fs::read_to_string(dir.join("Keel.toml")).unwrap())
            .unwrap();
    assert_eq!(parsed.package.name, "legacy-app");
    assert_eq!(parsed.package.edition, "2024");
    let keel_text = std::fs::read_to_string(dir.join("Keel.toml")).unwrap();
    assert!(keel_text.contains("authors = [\"Samar\"]"), "{keel_text}");
    assert!(
        !keel_text.contains("entry = \"src/main.lpp\""),
        "{keel_text}"
    );
    assert!(keel_text.contains("[dependencies]"), "{keel_text}");

    // 3. Migrating when BOTH Keel.toml and lpp.toml exist must fail safely.
    let both_err = keel::commands::migrate::migrate(&dir, false, false).unwrap_err();
    assert!(both_err.contains("both"), "unexpected error: {both_err}");

    // 4. Clean migration removes lpp.toml + lpp.lock.
    std::fs::remove_file(dir.join("Keel.toml")).unwrap();
    std::fs::remove_file(dir.join("Keel.lock")).unwrap();
    keel::commands::migrate::migrate(&dir, false, false).unwrap();
    assert!(dir.join("Keel.toml").is_file());
    assert!(dir.join("Keel.lock").is_file());
    assert!(!dir.join("lpp.toml").exists());
    assert!(!dir.join("lpp.lock").exists());

    let parsed_lock =
        lpp_pm::Lock::parse(&std::fs::read_to_string(dir.join("Keel.lock")).unwrap()).unwrap();
    assert_eq!(parsed_lock.lock_version, lpp_pm::lock::LOCK_VERSION);

    // 5. Idempotent second run when already at Keel.toml.
    keel::commands::migrate::migrate(&dir, false, false).unwrap();

    // 6. Workspace discovers the migrated manifest cleanly.
    let ws = lpp_pm::Workspace::discover(&dir).unwrap();
    assert_eq!(ws.members.len(), 1);
    assert_eq!(ws.members[0].name(), "legacy-app");

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn migrate_workspace_and_members_together() {
    let dir = temp("workspace");
    std::fs::create_dir_all(dir.join("crates/corelib/src")).unwrap();
    std::fs::create_dir_all(dir.join("crates/app/src")).unwrap();

    std::fs::write(
        dir.join("lpp.toml"),
        "[workspace]\nmembers = [\"crates/*\"]\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("crates/corelib/lpp.toml"),
        "[package]\nname = \"corelib\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("crates/app/lpp.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n[dependencies]\ncorelib = { path = \"../corelib\" }\n",
    )
    .unwrap();

    // Legacy workspace discovery still works prior to migration.
    let legacy_ws = lpp_pm::Workspace::discover(&dir).unwrap();
    assert_eq!(legacy_ws.members.len(), 2);

    // Migrate whole workspace in one call.
    keel::commands::migrate::migrate(&dir, false, false).unwrap();
    assert!(dir.join("Keel.toml").is_file());
    assert!(!dir.join("lpp.toml").exists());
    assert!(dir.join("crates/corelib/Keel.toml").is_file());
    assert!(!dir.join("crates/corelib/lpp.toml").exists());
    assert!(dir.join("crates/app/Keel.toml").is_file());
    assert!(!dir.join("crates/app/lpp.toml").exists());

    let modern_ws = lpp_pm::Workspace::discover(&dir).unwrap();
    assert_eq!(modern_ws.members.len(), 2);
    let plan = modern_ws.build_plan().unwrap();
    assert_eq!(plan.len(), 2);

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn migrate_errors_when_no_manifest_present() {
    let dir = temp("empty");
    let err = keel::commands::migrate::migrate(&dir, false, false).unwrap_err();
    assert!(err.contains("no lpp.toml or Keel.toml"), "{err}");
    let _ = std::fs::remove_dir_all(&dir);
}
